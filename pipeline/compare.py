"""Compare fetched events with shows.json and describe the differences.

Nothing here edits shows.json — the routine reads the report, applies the judgment
rules in pipeline/INSTRUCTIONS.md, and makes the edits itself.
"""
import difflib
import re

from .common import norm

FIELD_MAP = {"doors": "dr", "show": "sh", "price": "p", "price_dos": "dop", "stage": "s", "url": "u"}


def _core(name):
    """The act name without tour subtitles, 'presents', tribute notes, etc."""
    n = re.split(r"\s+[—–-]\s+|:\s+|\s+\(|\s+w/\s+|\s+\+\s+|\s+/\s+|\s+with special guest", name or "", maxsplit=1)[0]
    n = re.sub(r"^(?:live at firefly with|limbo at the refinery presents)\s+", "", n, flags=re.I)
    return norm(n)


def same_act(a, b):
    x, y = _core(a), _core(b)
    if not x or not y:
        return False
    if x == y or x.startswith(y) or y.startswith(x):
        return True
    fa, fb = norm(a), norm(b)
    if len(x) >= 6 and (x in fb or y in fa):
        return True
    # Same letters in a different order catches typos like the venue's "Tuak" for TAUK.
    # Only ever compared within one venue and date, so a short anagram is low-risk.
    if len(x) >= 4 and sorted(x) == sorted(y):
        return True
    return difflib.SequenceMatcher(None, x[:24], y[:24]).ratio() >= 0.8


def compare(shows, venue, events, complete, today):
    rows = [s for s in shows if s["v"] == venue]
    upcoming = [e for e in events if e.get("date") and e["date"] >= today]
    matched_rows = set()
    out = {"new": [], "skipped_new": [], "updates": [], "date_changes": [], "missing": []}

    for e in upcoming:
        hit = next((i for i, s in enumerate(rows) if s["d"] == e["date"] and same_act(s["b"], e["title"])), None)
        if hit is None:
            # Same act on a different nearby date: a possible date change.
            near = [i for i, s in enumerate(rows) if s["d"] >= today and same_act(s["b"], e["title"])
                    and i not in matched_rows]
            moved = next((i for i in near if not any(x["date"] == rows[i]["d"] and same_act(rows[i]["b"], x["title"])
                                                     for x in upcoming)), None)
            if moved is not None and not e.get("skip"):
                matched_rows.add(moved)
                out["date_changes"].append({"row": rows[moved], "event": e})
                continue
            out["skipped_new" if e.get("skip") else "new"].append(e)
            continue
        matched_rows.add(hit)
        s = rows[hit]
        diffs = {}
        for ek, sk in FIELD_MAP.items():
            if ek in e and e[ek] != s.get(sk):
                if sk == "u" and s.get(sk):
                    continue   # keep an existing link unless a person decides otherwise
                if sk == "s" and s.get(sk) and norm(s[sk]).startswith(norm(e[ek])[:4]):
                    continue
                diffs[sk] = {"file": s.get(sk), "source": e[ek]}
        if e.get("status") in ("sold out", "low tix") and not s.get("soldOut" if e["status"] == "sold out" else "lowTix"):
            diffs["status"] = {"file": None, "source": e["status"]}
        if diffs:
            out["updates"].append({"row": s, "event": e, "fields": diffs})

    if complete and upcoming:
        last = max(e["date"] for e in upcoming)
        for i, s in enumerate(rows):
            if i in matched_rows or not (today <= s["d"] <= last):
                continue
            if any(e["date"] == s["d"] and same_act(s["b"], e["title"]) for e in upcoming):
                continue
            out["missing"].append(s)
    out["coverage"] = [min((e["date"] for e in upcoming), default=None), max((e["date"] for e in upcoming), default=None)]
    return out


def _ev(e):
    bits = [e["date"], e["title"]]
    for k in ("stage", "doors", "show"):
        if e.get(k):
            bits.append(f"{k} {e[k]}")
    if e.get("price") is not None:
        bits.append(f"${e['price']}" + (f"/${e['price_dos']} DOS" if e.get("price_dos") is not None else ""))
    if e.get("status"):
        bits.append(e["status"])
    if e.get("url"):
        bits.append(e["url"])
    return " · ".join(str(b) for b in bits)


def report_markdown(results, today):
    lines = [f"# Fetch report — {today}", "",
             "Generated by `python3 -m pipeline.run`. Each venue lists what its source shows that "
             "shows.json doesn't, and the reverse. Apply pipeline/INSTRUCTIONS.md to decide what to change.", ""]
    for venue, r in results.items():
        lines.append(f"## {venue} — {r['source']}")
        if r.get("error"):
            lines += ["", f"**Source failed:** {r['error']}. Don't add or remove {venue} rows from this report; "
                      "follow the venue's fallback in INSTRUCTIONS.md.", ""]
            continue
        c = r["comparison"]
        cov = c["coverage"]
        lines.append(f"{r['count']} upcoming events listed ({cov[0]} → {cov[1]}); "
                     f"{'complete listing' if r['complete'] else 'partial listing (never use for removals)'}.")
        for title, key in (("New (not in shows.json)", "new"), ("Date changes", "date_changes"),
                           ("Field updates", "updates"), ("In shows.json but not listed", "missing"),
                           ("Not added — looks out of scope", "skipped_new")):
            items = c[key]
            if not items:
                continue
            lines += ["", f"**{title}** ({len(items)})"]
            for it in items:
                if key in ("new", "skipped_new"):
                    lines.append(f"- {_ev(it)}" + (f" — _{it['skip']}_" if it.get("skip") else ""))
                elif key == "date_changes":
                    lines.append(f"- {it['row']['b']}: {it['row']['d']} → {it['event']['date']}")
                elif key == "updates":
                    f = "; ".join(f"{k}: {v['file']!r} → {v['source']!r}" for k, v in it["fields"].items())
                    lines.append(f"- {it['row']['d']} {it['row']['b']}: {f}")
                else:
                    lines.append(f"- {it['d']} {it['b']}")
        lines.append("")
    return "\n".join(lines) + "\n"
